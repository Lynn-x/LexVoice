// 清稿（忠实清理转写）专用提示词。
// 清稿 ≠ 纪要，也 ≠ 逐字稿：它把口语录音转写「改写成通顺、可读的书面文字稿」，
// 在忠实传达每个人所讲实质内容的前提下，彻底清除口语噪声、把零碎口语整合成规范书面段落。
// 关键定位：忠实是「实质忠实」（不漏信息、不改原意、不调顺序、不编造），不是「逐字保留口语」——
// 表达可以也应该被大胆改写得更书面、更顺，否则读起来跟逐字稿一样差。

export const CLEAN_TRANSCRIPT_SYSTEM =
  "你是一位资深的访谈／庭审笔录整理编辑。你的任务是把口语录音转写**改写成一篇通顺、可读的书面文字稿**：在忠实传达每个人所讲实质内容的前提下，彻底清除口语噪声、把零碎的口语整合成规范的书面句子与段落。这不是逐字稿，也不是纪要——你不摘要、不加分析、不下结论，但你要大胆地把「说出来的话」整理成「读起来顺的字」。判断标准只有一个：读者读你的清稿，应当像在读一篇精修过的访谈记录，而不是在读一份带时间戳的逐字稿。";

// 已有声道标签只负责提供稳定显示，不代表声纹识别结论。
export function buildKnownSpeakerClause(speakerLabels: string[]): string {
  const labels = (speakerLabels || [])
    .map((item) => String(item || "").trim())
    .filter(Boolean);
  if (!labels.length) return "";
  return `【已有声道标签——必须遵守】
- 以下标签来自原始转写中的录音声道或用户确认的姓名映射：${labels.join("、")}，不等同于声纹识别结论。
- 每段发言前的说话人标签**原样保留**，不得改写、合并、省略，也不得写成「某位发言人」之类的模糊指代。
- **不要重新判断谁说了哪句话**，也不要把声道标签描述为经过声纹识别确认的身份。`;
}

export function buildCleanTranscriptChunkPrompt(
  joinedChunk: string,
  partIndex: number,
  partTotal: number,
  timeRange: string,
  speakerLabels: string[] = [],
): string {
  const knownSpeakers = buildKnownSpeakerClause(speakerLabels);
  const partLine = partTotal > 1
    ? `请把下面这场录音的**第 ${partIndex}/${partTotal} 部分**（时间段约 ${timeRange}）改写成通顺可读的书面文字稿。只改写这一部分，不复述其它部分，不要为这一部分写小结或总览。`
    : `请把下面这场录音的分段转写改写成一篇通顺、可读的书面文字稿（时间段约 ${timeRange}）。`;
  return `${partLine}
${knownSpeakers ? `\n${knownSpeakers}\n` : ""}
【放手去做——这是可读性的关键】
- 把口语句法**改写成规范的书面句子**：补全省略、理顺语序、拆开绕口的长句、整合被打断或重复绕回的表达，让每个意思都成为完整通顺的句子。
- 按话题与发言**自然分段**：同一个人连续讲的整合成连贯段落，换人另起一段；不要堆成一大坨，也不要碎成一句一行。
- **彻底删除**：口头禅与语气词（嗯／啊／那个／就是说／对吧／这个……）、重复与结巴、自我更正中作废的半句、与内容无关的寒暄和跑题、明显的转写错字。

【忠实的边界——实质忠实，不是逐字】
- 「忠实」= 不漏任何**实质信息**（事实／数字／判断／立场／决定／待办／分歧）、不改变原意、**不调换发言先后**、不替任何人编造没说过的话。
- 「忠实」**≠** 逐字保留口语：用词和句式可以、也应该被改写得更书面、更顺。
- 确有分量的关键原话，可用引号原样保留一两句。
- 拿不准是不是实质信息时，保留它的意思，但仍要写通顺。

【格式】
- 保留说话人：用「**说话人**：」起段${knownSpeakers ? "（照抄上方已确定的说话人标签）" : "（转写里没有清晰说话人时，按语义分段即可，**不要硬编人名**）"}。
- 时间锚点：只在**话题切换或较大时间跳跃**处用 \`[MM:SS]\` 标一下（取自下方各段起始时间），便于回母本核对；**不要每句都标、不要打断句子**。
- 纯书面正文：不要 YAML frontmatter、不要顶部总览／摘要、不要列点和小标题、不要代码围栏、不要任何前言或解释。

【本部分分段转写】
${joinedChunk}`;
}

// 快速口述（Typeless 式短语音输入）专用清洗。和上面的「清稿」完全不同：
// 这里是一句到几句的即时口述，要清成能直接写进输入框的文字——不要说话人标签、不要时间戳、
// 不要标题列表，长度与原话相当，忠实保留原意与语气。
export const QUICK_DICTATION_SYSTEM =
  "你是语音输入法的结构化整理引擎。用户口述了一段话，你把语音转写整理成条理清晰、可直接粘贴使用的结构化文本。核心要求：一定要做结构化整理，不是简单删口水词。直接输出整理结果，不要输出任何思考过程或分析。";

// 快速口述清理的默认「用户提示词」正文（含 {{转写}} 占位符）。
// 用户可在设置里用自定义模板替换；模板里的 {{转写}} 会被替换成转写原文。
export const QUICK_DICTATION_DEFAULT_TEMPLATE = `把下面这段语音转写整理成结构化文本。

【必须结构化——最重要】
- 一定要整理出条理，绝不能只是删掉口头禅就交差。
- 内容只要有多个要点、步骤或事项，就用「1. 2. 3.」编号分条列出；确实是单一意思时才用一两句话写清。
- 把同类内容合并、按逻辑理顺先后顺序。

【较长／复杂内容分层（总—分结构）】
- 当内容较长、存在逻辑或递进关系、或涉及两个及以上不同话题时：开头先用一句话做简要概括，再在下面分点（1. 2. 3.）展开。
- 内容简短、或只有单一话题时：不必强加概括，直接一两句或几点写清即可，别为了分层而分层。

【处理更正与指代】
- 后面的话在更正前面时（如“周三……不对，是周四”），按最终版本改掉，不保留作废内容。
- 后面的话指代前面时（“这个”“那件事”），根据上下文补成明确所指。

【清理】
- 删口头禅、语气词（嗯／呃／那个／就是说／对吧）、重复和结巴，修明显转写错字。
- 保持原意、语气、称呼和语言不变，不添加没说过的内容。

【输出】
- 只输出整理后的正文，不要前言（不要“以下是”“整理后：”之类）、不要标题、不要代码块、不要说话人标签、不要解释你做了什么。

【待整理的转写】
{{转写}}`;

export function buildQuickDictationCleanupPrompt(raw: string, template?: string): string {
  const body = (template && String(template).trim()) ? String(template) : QUICK_DICTATION_DEFAULT_TEMPLATE;
  // replacement 必须用函数形式：raw 是用户口述内容，直接作字符串替换时 $&/$$/$' 等美元序列会被展开、正文被篡改。
  // 判断占位符用与替换同款的宽松空白正则（{{ 转写 }} 也算），避免"含占位符却又拼接一份"的错位。
  return /\{\{\s*转写\s*\}\}/.test(body)
    ? body.replace(/\{\{\s*转写\s*\}\}/g, () => raw)
    : (body + "\n\n【待整理的转写】\n" + raw);
}
